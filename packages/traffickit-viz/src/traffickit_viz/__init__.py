"""TrafficKit 的視覺化與影片輸出層。

**目前是骨架，還沒有公開函式。** 這一版建立的是套件結構、相依邊界與
測試框架；功能會逐項搬進來。

為什麼獨立成一個套件
--------------------

`traffickit` 只依賴 pandas 與 numpy，因此後端服務、CI 與 Jupyter 都裝得動。
視覺化需要 OpenCV（安裝後數百 MB）、影片編解碼，往後還會有 GUI。把這些
放進核心，等於讓每一個只想算轉向流量的人都被迫安裝一整套影像處理相依。

分工
----

======================  ==========================================
放這裡                  留在 ``traffickit``
======================  ==========================================
影片解碼與編碼          軌跡檔讀取（``traffickit.formats``）
bbox 繪製與疊圖         交通計算（``speed``、``volume``）
顏色、標籤、箭頭樣式    會改變交通結果意義的判定
比例尺（公尺 → 像素）   單位契約本身（m/s、秒、公尺）
互動介面與預覽          —
命令列參數剖析          —
======================  ==========================================

判準是「這段邏輯改變的是**畫面**還是**數字**」。改變數字的留在核心，
改變畫面的放這裡。

相依方向
--------

``traffickit_viz`` 可以 import ``traffickit``；**``traffickit`` 永遠不可以
import ``traffickit_viz``**。這條線一旦反過來，上面說的好處立刻消失，而且
不會有任何功能測試失敗——所以核心的 ``tests/test_layering.py`` 專門守它。
"""

